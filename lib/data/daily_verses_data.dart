DailyVerse getDailyVerse([DateTime? time]) {
  final now = time ?? DateTime.now();
  // Berganti setiap 8 jam: (00:00-08:00, 08:00-16:00, 16:00-24:00)
  final dayNumber = now.year * 366 + now.month * 31 + now.day;
  final period = now.hour ~/ 8; // 0, 1, 2
  final index = (dayNumber * 3 + period) % dailyVersesList.length;
  return dailyVersesList[index];
}

String getDailyVersePeriodLabel([DateTime? time]) {
  final now = time ?? DateTime.now();
  final period = now.hour ~/ 8;
  if (period == 0) return 'Pagi Dini (00:00 - 08:00)';
  if (period == 1) return 'Siang Hari (08:00 - 16:00)';
  return 'Malam Hari (16:00 - 24:00)';
}

